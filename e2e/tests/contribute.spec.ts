import { expect, test, type Page } from '@playwright/test';
import { DATABASE_URL, signInAs, testWav } from './support.js';

// The whole contribution lifecycle, in order:
// submit -> moderate -> publish -> takedown -> unpublished.
test.describe.configure({ mode: 'serial' });
test.skip(!DATABASE_URL, 'Set E2E_DATABASE_URL to run signed-in flows');

const city = `E2E City ${Date.now()}`;
const title = `E2E hum ${Date.now()}`;
let recordingUrl = '';

/** Exact label match, ignoring the visual "*" required fields carry. */
const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const label = (text: string) => new RegExp(`^${escapeRegExp(text)}\\s*\\*?$`);

async function fill(page: Page, text: string, value: string) {
  await page.getByLabel(label(text)).fill(value);
}

test('visitors are sent to sign in, contributors cannot see moderation', async ({ page, context, baseURL }) => {
  await page.goto('/contribute');
  await expect(page).toHaveURL(/\/signin\?returnTo=%2Fcontribute/);
  await expect(page.getByRole('heading', { name: 'Sign in', level: 2 })).toBeVisible();

  await signInAs(context, baseURL!, { name: 'E2E Visitor' });
  const res = await page.goto('/moderation');
  expect(res?.status()).toBe(404);
});

test('email sign-in sends a one-time link', async ({ page }) => {
  await page.goto('/signin');
  // Unique per run: the form allows only a few links per address per 15 minutes.
  await page.getByLabel('Email address').fill(`e2e-${Date.now()}@example.com`);
  await page.getByRole('button', { name: 'Email me a sign-in link' }).click();
  await expect(page.getByRole('heading', { name: 'Check your email' })).toBeVisible();
});

test('a contributor uploads, describes and submits a recording', async ({ page, context, baseURL }) => {
  test.setTimeout(120_000);
  await signInAs(context, baseURL!, { name: 'E2E Contributor' });
  await page.goto('/contribute');
  await page.getByRole('button', { name: /New recording/ }).click();
  // A dev server compiles the editor route on first visit; allow for it.
  await expect(page).toHaveURL(/\/contribute\/[0-9a-f-]{36}$/, { timeout: 60_000 });

  // 1. Audio: uploaded straight to storage through a signed URL, then processed.
  await page.locator('input[type=file]').setInputFiles({ name: 'hum.wav', mimeType: 'audio/wav', buffer: testWav(3) });
  await expect(page.getByText('Audio ready')).toBeVisible({ timeout: 60_000 });

  // 2–5. Metadata (autosaved).
  await fill(page, 'Title (English)', title);
  await page.getByLabel(label('Kind of sound')).selectOption('street');
  await fill(page, 'What you hear (English)', 'A steady two-tone hum generated for automated testing.');
  await fill(page, 'Place (English)', 'Test square');
  await fill(page, 'City (English)', city);
  await fill(page, 'Country code', 'GB');
  await fill(page, 'Latitude', '51.5072');
  await fill(page, 'Longitude', '-0.1276');
  await fill(page, 'Year it represents', '1975');
  await fill(page, 'Captured from', '2026-10-01');
  await fill(page, 'Captured until', '2026-10-01');
  await page.getByLabel(label('How sure is the date?')).selectOption('exact');
  // Made recently to evoke the 1970s, so it must be a labelled reconstruction.
  await page.getByLabel(label('Source')).selectOption('community_reconstruction');
  await fill(page, 'How was it made?', 'Two sine tones generated by the end-to-end test suite.');
  await page.getByLabel(label('License')).selectOption('cc0');
  await page.getByLabel(label('Rights')).selectOption('contributor_owns');
  await fill(page, 'Rights holder', 'E2E Contributor');
  await fill(page, 'Credit line', 'E2E Contributor, CC0');
  await page.getByLabel(label('Voices in the recording')).selectOption('no_identifiable_speech');

  await expect(page.getByText('All changes saved')).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText("Everything's filled in.")).toBeVisible({ timeout: 15_000 });

  // Review & submit.
  await page.getByLabel(/right to share this recording/).check();
  await page.getByLabel(/provenance I gave is accurate/).check();
  await page.getByLabel(/No identifiable private person/).check();
  await page.getByRole('button', { name: 'Submit for review' }).click();
  await expect(page.getByText('Submitted. A moderator will review it.')).toBeVisible();
  await expect(page.getByText('In review.', { exact: false }).first()).toBeVisible();
});

test('a moderator approves it with the full checklist', async ({ page, context, baseURL }) => {
  await signInAs(context, baseURL!, { name: 'E2E Moderator', role: 'moderator' });
  await page.goto('/moderation');
  await page.getByRole('link', { name: new RegExp(title) }).click();
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible();

  const approve = page.getByRole('button', { name: 'Approve & publish' });
  await expect(approve).toBeDisabled();
  for (const item of ['Audio quality', 'Rights confirmed', 'Location accurate', 'No private speech without consent']) {
    await page.getByLabel(item).check();
  }
  await approve.click();
  await expect(page).toHaveURL(/\/moderation$/);
  await expect(page.getByText('Published.')).toBeVisible();
});

test('the published recording is public, with its reconstruction label', async ({ page }) => {
  await page.goto(`/list?q=${encodeURIComponent(city)}`);
  await page.getByRole('link', { name: title }).click();
  await page.waitForURL(/\/recordings\/[0-9a-f-]{36}$/);
  recordingUrl = page.url();
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible();
  await expect(page.getByText(/not an authentic recording from this era/)).toBeVisible();
  await expect(page.getByText('Two sine tones generated by the end-to-end test suite.')).toBeVisible();
});

test('a takedown request lets a moderator unpublish it', async ({ page, browser, baseURL }) => {
  // The public files a request from the recording page.
  await page.goto(recordingUrl);
  await page.getByRole('link', { name: 'Request removal' }).click();
  await fill(page, 'Your name', 'E2E Rights Holder');
  await fill(page, 'Your email', 'rights@example.com');
  await page.getByLabel(label('Reason')).selectOption('copyright');
  await fill(page, 'Details', 'This test recording reproduces our test tone without permission.');
  await page.getByLabel(/I believe in good faith/).check();
  await page.getByRole('button', { name: 'Send request' }).click();
  await expect(page.getByText('Request received')).toBeVisible();

  // A moderator acts on it.
  const modContext = await browser.newContext();
  await signInAs(modContext, baseURL!, { name: 'E2E Moderator 2', role: 'moderator' });
  const mod = await modContext.newPage();
  await mod.goto('/moderation?tab=takedowns');
  const card = mod.getByRole('article').filter({ hasText: title });
  await card.getByLabel('Resolution note (internal)').fill('Verified with the claimant.');
  await card.getByRole('button', { name: 'Unpublish recording' }).click();
  await expect(mod.getByText('Recording unpublished and request closed.')).toBeVisible();
  await modContext.close();

  const res = await page.goto(recordingUrl);
  expect(res?.status()).toBe(404);
});
